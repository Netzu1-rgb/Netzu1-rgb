// Helper: Retrieve translation with fallback chain (lang -> en -> es -> key)
export function getTranslation(lang, key, params = {}) {
  let text = TRANSLATIONS[lang]?.[key] || TRANSLATIONS['en']?.[key] || TRANSLATIONS['es']?.[key] || key;
  
  if (params && typeof params === 'object') {
    Object.keys(params).forEach(k => {
      text = text.replace(new RegExp(`{{${k}}}`, 'g'), params[k]);
    });
  }
  return text;
}
