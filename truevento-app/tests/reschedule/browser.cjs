// Admins move a class (rain) from Solicitudes; the student sees it; instructors cannot.
// Needs the local stack with the e2e data. Usage: node tests/reschedule/browser.cjs
const { chromium } = require('playwright')
const { execFileSync } = require('child_process')
const sql = (q) => execFileSync('psql', ['-h', '127.0.0.1', '-p', '54322', '-U', 'postgres', '-d', 'postgres', '-XtAc', q], { env: { PGPASSWORD: 'postgres', PATH: process.env.PATH }, encoding: 'utf8' }).trim()
const res = []; const check = (n, c, x = '') => res.push([n, c, x])
;(async () => {
  const b = await chromium.launch(); const errs = []
  const c = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, locale: 'es-AR' })
  // ---- management: move Julia's class because of rain
  const g = await c.newPage(); g.on('pageerror', (e) => errs.push(e.message))
  await g.goto('http://127.0.0.1:5173'); await g.getByLabel('Usuario o email').fill('victoria@truevento.com'); await g.getByLabel('Contraseña').fill('Kite2026!')
  await g.getByRole('button', { name: 'Ingresar' }).click(); await g.locator('main').waitFor(); await g.waitForTimeout(1500)
  await g.goto('http://127.0.0.1:5173/solicitudes'); await g.waitForTimeout(3000)
  check('upcoming classes listed', await g.getByText('Próximas clases').count() === 1)
  const row = g.locator('li').filter({ hasText: 'Julia Paz' })
  check('Julia in the list', await row.count() === 1)
  await row.scrollIntoViewIfNeeded(); await g.screenshot({ path: __dirname + '/r-1-list.png' })
  await row.getByRole('button', { name: 'Cambiar fecha' }).click(); await g.waitForTimeout(800)
  const d = g.locator('dialog')
  await d.getByRole('button', { name: 'Lluvia' }).click()
  const newDate = sql(`select to_char(current_date + 3, 'YYYY-MM-DD')`)
  await d.getByLabel('Nuevo día').fill(newDate); await g.waitForTimeout(700)
  await d.getByLabel('Horario').selectOption('16:00')
  await g.screenshot({ path: __dirname + '/r-2-modal.png' })
  await d.getByRole('button', { name: 'Guardar nueva fecha' }).click(); await g.waitForTimeout(2000)
  check('done screen', await g.getByText('Clase cambiada').count() >= 1)
  const wa = await g.getByRole('link', { name: 'Avisar por WhatsApp' }).getAttribute('href')
  const text = decodeURIComponent(wa.split('text=')[1])
  check('WhatsApp message with the reason', /^¡Hola, Julia! Te escribimos de Truevento Kiteschool\. Por el pronóstico de lluvia, pasamos tu clase al .+ a las 16:00\. ¿Te queda bien\?$/.test(text), text)
  await g.screenshot({ path: __dirname + '/r-3-done.png' })
  const row2 = sql(`select l.lesson_date = current_date + 3, to_char(l.start_time,'HH24:MI'), l.staff_note from public.lessons l join public.students s on s.id=l.student_id where s.full_name='Julia Paz' and l.status='confirmed'`)
  check('saved: new day, time and reason', row2 === 't|16:00|Pronóstico de lluvia', row2)
  // ---- the student sees the new day and the reason
  const j = await c.newPage(); j.on('pageerror', (e) => errs.push(e.message))
  await (await c.newPage()).close()
  await j.goto('http://127.0.0.1:5174'); await j.waitForTimeout(1500)
  if (await j.getByLabel('Contraseña').count()) { await j.getByLabel('Usuario').fill('julia'); await j.getByLabel('Contraseña').fill('Kitesurf1') ; await j.getByRole('button', { name: 'Entrar', exact: true }).click() }
  await j.waitForTimeout(2500)
  await j.goto('http://127.0.0.1:5174/agenda'); await j.waitForTimeout(2000)
  check('student sees 16:00 and the reason', await j.getByText('Pronóstico de lluvia').count() >= 1 && await j.getByText(/16:00/).count() >= 1)
  // ---- an instructor cannot move classes
  const i = await (await b.newContext({ viewport: { width: 390, height: 844 }, locale: 'es-AR' })).newPage()
  await i.goto('http://127.0.0.1:5174'); await i.getByLabel('Usuario').fill('lucas'); await i.getByLabel('Contraseña').fill('Instructor1'); await i.getByRole('button', { name: 'Entrar', exact: true }).click()
  await i.locator('main').waitFor(); await i.waitForTimeout(1500)
  await i.goto('http://127.0.0.1:5174/agenda'); await i.waitForTimeout(2000)
  check('instructor: no "Cambiar fecha"', await i.getByRole('button', { name: 'Cambiar fecha' }).count() === 0 && await i.getByRole('button', { name: 'Cancelar' }).count() >= 1)
  check('no page errors', !errs.length, errs.join(' | '))
  console.log(res.map(([n, ok, x]) => (ok ? 'OK   ' : 'FAIL ') + n + (ok ? '' : ' → ' + x)).join('\n'))
  console.log(res.every((r) => r[1]) ? 'RESCHED OK' : 'RESCHED FAIL')
  await b.close()
})().catch((e) => { console.error(e); process.exit(1) })
